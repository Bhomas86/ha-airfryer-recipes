"""Authenticated Home Assistant WebSocket API for device-independent recipes.

Read access: authenticated HA users.
Shared recipe mutations and imports: administrators only, enforced by Home
Assistant's built-in require_admin decorator. Each authenticated user may
change only their own personal favorites. No appliance calls.
"""

from __future__ import annotations

from datetime import timedelta
import logging
from dataclasses import replace
from typing import Any, Awaitable, Callable
from uuid import uuid4

import probatio

from homeassistant.components import websocket_api

from .const import DOMAIN, EXPORT_FILENAME, EXPORT_URL
from .recipe_model import (
    MAX_IMPORT_BYTES,
    RecipeValidationError,
    recipe_from_dict,
    recipe_to_dict,
)
from .recipe_repository import (
    PREVIEW_TTL_SECONDS,
    RecipeConflictError,
    RecipeNotFoundError,
    RecipePreviewExpiredError,
    RecipeRepository,
)

_LOGGER = logging.getLogger(__name__)
_ACTION = Callable[[RecipeRepository], Awaitable[dict[str, Any]]]
EXPORT_LINK_TTL_SECONDS = 30


def _repository(hass: Any, connection: Any, msg: dict[str, Any]) -> RecipeRepository | None:
    """Resolve a loaded library without trusting a user-supplied entry ID."""
    if connection.user is None:
        connection.send_error(msg["id"], websocket_api.ERR_UNAUTHORIZED, "Authentication required")
        return None
    state = hass.data.get(DOMAIN, {})
    repository = state.get("repository")
    if repository is None:
        connection.send_error(msg["id"], "not_configured", "Airfryer Recipes is not configured")
    return repository


async def _respond(
    hass: Any,
    connection: Any,
    msg: dict[str, Any],
    action: _ACTION,
) -> None:
    """Send one structured result or an error without leaking internals."""
    repository = _repository(hass, connection, msg)
    if repository is None:
        return
    try:
        result = await action(repository)
    except RecipePreviewExpiredError:
        connection.send_error(msg["id"], "preview_expired", "Import preview expired or library changed")
    except RecipeNotFoundError:
        connection.send_error(msg["id"], websocket_api.ERR_NOT_FOUND, "Recipe not found")
    except RecipeConflictError as err:
        connection.send_error(msg["id"], "recipe_conflict", str(err))
    except RecipeValidationError as err:
        connection.send_error(msg["id"], websocket_api.ERR_INVALID_FORMAT, str(err))
    except (KeyError, TypeError, ValueError):
        connection.send_error(msg["id"], websocket_api.ERR_INVALID_FORMAT, "Invalid recipe parameters")
    except Exception:
        _LOGGER.exception("Recipe operation failed")
        connection.send_error(msg["id"], "storage_error", "Recipe operation failed; check Home Assistant logs")
    else:
        connection.send_result(msg["id"], result)


@websocket_api.websocket_command({probatio.Required("type"): f"{DOMAIN}/list"})
@websocket_api.async_response
async def ws_list(hass: Any, connection: Any, msg: dict[str, Any]) -> None:
    """Read saved recipes; device selection is not part of the recipe."""
    async def run(repo: RecipeRepository) -> dict[str, Any]:
        return {"recipes": [recipe_to_dict(r) for r in await repo.async_list()]}
    await _respond(hass, connection, msg, run)


@websocket_api.websocket_command({
    probatio.Required("type"): f"{DOMAIN}/get",
    probatio.Required("recipe_id"): str,
})
@websocket_api.async_response
async def ws_get(hass: Any, connection: Any, msg: dict[str, Any]) -> None:
    """Return a single recipe."""
    async def run(repo: RecipeRepository) -> dict[str, Any]:
        return {"recipe": recipe_to_dict(await repo.async_get(msg["recipe_id"]))}
    await _respond(hass, connection, msg, run)


@websocket_api.require_admin
@websocket_api.websocket_command({
    probatio.Required("type"): f"{DOMAIN}/create",
    probatio.Required("recipe"): dict,
})
@websocket_api.async_response
async def ws_create(hass: Any, connection: Any, msg: dict[str, Any]) -> None:
    """Create a new recipe with a server-generated ID (admins only)."""
    async def run(repo: RecipeRepository) -> dict[str, Any]:
        raw = msg["recipe"]
        if "id" in raw:
            raise RecipeValidationError("recipe ID must be generated by the server")
        recipe = recipe_from_dict({**raw, "id": str(uuid4())})
        return {"recipe": recipe_to_dict(await repo.async_create(recipe))}
    await _respond(hass, connection, msg, run)


