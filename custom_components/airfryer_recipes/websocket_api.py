_LOGGER = logging.getLogger(__name__)
_ACTION = Callable[[RecipeRepository], Awaitable[dict[str, Any]]]
EXPORT_LINK_TTL_SECONDS = 30


def _repository(hass: Any, connection: Any, msg: dict[str, Any]) -> RecipeRepository | None:
    """Resolve a loaded library without trusting a user-supplied entry ID."""
    if connection.user is None:
        connection.send_error(msg["id"], websocket_api.ERR_UNAUTHORIZED, "Authentication required")
        return None
    state = hass.data.get(DOMAIN, {})
    repository = state.get("repository")
    if repository is None:
        connection.send_error(msg["id"], "not_configured", "Airfryer Recipes is not configured")
    return repository


async def _respond(
    hass: Any,
    connection: Any,
    msg: dict[str, Any],
    action: _ACTION,
) -> None:
    """Send one structured result or an error without leaking internals."""
    repository = _repository(hass, connection, msg)
    if repository is None:
        return
    try:
        result = await action(repository)
    except BetaTestBlocked as err:
        connection.send_error(msg["id"], "beta_test_blocked", str(err))
    except PreviewTargetNotFound:
        connection.send_error(msg["id"], "target_not_found", "Device or reported zone not found")
    except RecipePreviewExpiredError:
        connection.send_error(msg["id"], "preview_expired", "Import preview expired or library changed")
    except RecipeNotFoundError:
        connection.send_error(msg["id"], websocket_api.ERR_NOT_FOUND, "Recipe not found")
    except RecipeConflictError as err:
        connection.send_error(msg["id"], "recipe_conflict", str(err))
    except RecipeValidationError as err:
        connection.send_error(msg["id"], websocket_api.ERR_INVALID_FORMAT, str(err))
    except (KeyError, TypeError, ValueError):
        connection.send_error(msg["id"], websocket_api.ERR_INVALID_FORMAT, "Invalid recipe parameters")
    except Exception:
        _LOGGER.exception("Recipe operation failed")
        connection.send_error(msg["id"], "storage_error", "Recipe operation failed; check Home Assistant logs")
    else:
        connection.send_result(msg["id"], result)


@websocket_api.websocket_command({voluptuous.Required("type"): f"{DOMAIN}/list"})
@websocket_api.async_response
async def ws_list(hass: Any, connection: Any, msg: dict[str, Any]) -> None:
    """Read saved recipes; device selection is not part of the recipe."""
    async def run(repo: RecipeRepository) -> dict[str, Any]:
        return {"recipes": [recipe_to_dict(r) for r in await repo.async_list()]}
    await _respond(hass, connection, msg, run)


