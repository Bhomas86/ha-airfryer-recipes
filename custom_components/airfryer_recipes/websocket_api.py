@websocket_api.require_admin
@websocket_api.websocket_command({
    voluptuous.Required("type"): f"{DOMAIN}/create",
    voluptuous.Required("recipe"): dict,
})
@websocket_api.async_response
async def ws_create(hass: Any, connection: Any, msg: dict[str, Any]) -> None:
    """Create a new recipe with a server-generated ID (admins only)."""
    async def run(repo: RecipeRepository) -> dict[str, Any]:
        raw = msg["recipe"]
        if "id" in raw:
            raise RecipeValidationError("recipe ID must be generated by the server")
        recipe = recipe_from_dict({**raw, "id": str(uuid4())})
        return {"recipe": recipe_to_dict(await repo.async_create(recipe))}
    await _respond(hass, connection, msg, run)


